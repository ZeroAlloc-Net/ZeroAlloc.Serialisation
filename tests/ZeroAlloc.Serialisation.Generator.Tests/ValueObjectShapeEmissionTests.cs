    [Fact]
    public void TopLevelStruct_SystemTextJsonConverter_IsUnchanged()
    {
        var text = Generated(TopLevelStruct, "Demo.Inner.CustomerIdSystemTextJsonConverter.g.cs");

        AssertSameText("""
            // <auto-generated/>
            #nullable enable

            using System;
            using System.Text.Json;
            using System.Text.Json.Serialization;

            namespace Demo.Inner;

            [JsonConverter(typeof(CustomerIdSystemTextJsonConverter))]
            public readonly partial struct CustomerId
            {
            }

            internal sealed class CustomerIdSystemTextJsonConverter : JsonConverter<CustomerId>
            {
                public override CustomerId Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
                    => new CustomerId(reader.GetInt32());

                public override void Write(Utf8JsonWriter writer, CustomerId value, JsonSerializerOptions options)
                    => writer.WriteNumberValue(value.Value);
            }

            """, text);
    }

    private const string TimeSpans = """
        using ZeroAlloc.ValueObjects;
        namespace Demo;

        [ValueObject]
        public readonly partial struct Duration
        {
            public System.TimeSpan Value { get; }
            public Duration(System.TimeSpan value) => Value = value;
        }

        public partial class Shift
        {
            [ValueObject]
            public readonly partial struct Length
            {
                public System.TimeSpan Value { get; }
                public Length(System.TimeSpan value) => Value = value;
            }
        }
        """;

    // A TimeSpan has no Utf8JsonReader or Utf8JsonWriter overload. The converter formats and parses
    // the constant format as UTF-8 on the stack, culture-invariant and without a string.
    [Fact]
    public void TimeSpan_SystemTextJsonConverter_UsesUtf8FormatterAndParser()
    {
        var text = Generated(TimeSpans, "Demo.DurationSystemTextJsonConverter.g.cs");

        AssertSameText("""
            // <auto-generated/>
            #nullable enable

            using System;
            using System.Text.Json;
            using System.Text.Json.Serialization;

            namespace Demo;

            [JsonConverter(typeof(DurationSystemTextJsonConverter))]
            public readonly partial struct Duration
            {
            }

            internal sealed class DurationSystemTextJsonConverter : JsonConverter<Duration>
            {
                public override Duration Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
                {
                    if (reader.TokenType != JsonTokenType.String)
                        throw new JsonException("A TimeSpan must be a JSON string.");

                    // 26 bytes is the longest constant-format TimeSpan; escaped, each byte may take six.
                    const int MaxEscapedLength = 26 * 6;
                    var length = reader.HasValueSequence ? reader.ValueSequence.Length : reader.ValueSpan.Length;
                    if (length > MaxEscapedLength)
                        throw new JsonException("The JSON string is too long to be a TimeSpan.");

                    global::System.Span<byte> utf8 = stackalloc byte[MaxEscapedLength];
                    var written = reader.CopyString(utf8);
                    var text = utf8.Slice(0, written);
                    // Utf8Parser accepts leading and trailing characters System.Text.Json rejects; match it.
                    if (text.IsEmpty
                        || !(text[0] == (byte)'-' || (uint)(text[0] - '0') <= 9)
                        || (uint)(text[text.Length - 1] - '0') > 9
                        || !global::System.Buffers.Text.Utf8Parser.TryParse(text, out global::System.TimeSpan value, out var consumed, 'c')
                        || consumed != text.Length)
                        throw new JsonException("The JSON string is not a TimeSpan in the constant (c) format.");

                    return new Duration(value);
                }

                public override void Write(Utf8JsonWriter writer, Duration value, JsonSerializerOptions options)
                {
                    // 26 bytes is the longest constant-format TimeSpan, such as TimeSpan.MinValue.
                    global::System.Span<byte> utf8 = stackalloc byte[26];
                    global::System.Buffers.Text.Utf8Formatter.TryFormat(value.Value, utf8, out var written, 'c');
                    writer.WriteStringValue(utf8.Slice(0, written));
                }
            }

            """, text);
    }

    [Fact]
    public void TimeSpan_NestedOutput_HasNoTrailingWhitespace()
    {
        var result = RunGenerator(TimeSpans);

        Assert.Contains(result.GeneratedSources, static s => string.Equals(s.HintName, "Demo.Shift.LengthSystemTextJsonConverter.g.cs", StringComparison.Ordinal));
        foreach (var source in result.GeneratedSources)
        {
            var lines = source.SourceText.ToString().Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n');
            Assert.DoesNotContain(lines, static l => l.Length > 0 && char.IsWhiteSpace(l[^1]));
        }
    }

    [Fact]
    public void TopLevelStruct_MessagePackFormatter_IsUnchanged()
    {
        var text = Generated(TopLevelStruct, "Demo.Inner.CustomerIdMessagePackFormatter.g.cs");

        AssertSameText("""
            // <auto-generated/>
            #nullable enable

            using MessagePack;
            using MessagePack.Formatters;

            namespace Demo.Inner;

            [MessagePackFormatter(typeof(CustomerIdMessagePackFormatter))]
            public readonly partial struct CustomerId
            {
            }

            internal sealed class CustomerIdMessagePackFormatter : IMessagePackFormatter<CustomerId>
            {
                public void Serialize(ref MessagePackWriter writer, CustomerId value, MessagePackSerializerOptions options)
                    => writer.Write(value.Value);

                public CustomerId Deserialize(ref MessagePackReader reader, MessagePackSerializerOptions options)
                    => new CustomerId(reader.ReadInt32());
            }

            """, text);
    }

    [Fact]
    public void TopLevelStruct_MemoryPackFormatter_IsUnchanged()
    {
        var text = Generated(TopLevelStruct, "Demo.Inner.CustomerIdMemoryPackFormatter.g.cs");

        AssertSameText("""
            // <auto-generated/>
            #nullable enable

            using System.Runtime.CompilerServices;
            using MemoryPack;

            namespace Demo.Inner;

            internal static class CustomerIdMemoryPackFormatterRegistrar
            {
                [ModuleInitializer]
                internal static void Register()
                {
                    if (!MemoryPackFormatterProvider.IsRegistered<CustomerId>())
                    {
                        MemoryPackFormatterProvider.Register<CustomerId>(new CustomerIdMemoryPackFormatter());
                    }
                }
            }

            internal sealed class CustomerIdMemoryPackFormatter : MemoryPackFormatter<CustomerId>
            {
                public override void Serialize<TBufferWriter>(ref MemoryPackWriter<TBufferWriter> writer, scoped ref CustomerId value)
                    => writer.WriteValue<int>(value.Value);

                public override void Deserialize(ref MemoryPackReader reader, scoped ref CustomerId value)
                    => value = new CustomerId(reader.ReadValue<int>()!);
            }

            """, text);
    }

    [Fact]
    public void NestedRecordClass_IsDeclaredInsideItsContainingTypes()
    {
        var text = Generated(Nested, "Demo.Outer.Middle.DeepNameMessagePackFormatter.g.cs");

        AssertSameText("""
            // <auto-generated/>
            #nullable enable

            using MessagePack;
            using MessagePack.Formatters;

            namespace Demo;

            public partial class Outer
            {
                public readonly partial struct Middle
                {
                    [MessagePackFormatter(typeof(DeepNameMessagePackFormatter))]
                    public partial record DeepName
                    {
                    }

                    internal sealed class DeepNameMessagePackFormatter : IMessagePackFormatter<DeepName?>
                    {
                        public void Serialize(ref MessagePackWriter writer, DeepName? value, MessagePackSerializerOptions options)
                        {
                            if (value is null)
                            {
                                writer.WriteNil();
                                return;
                            }

                            writer.Write(value.Value);
                        }

                        public DeepName? Deserialize(ref MessagePackReader reader, MessagePackSerializerOptions options)
                            => reader.TryReadNil() ? null : new DeepName(reader.ReadString()!);
                    }
                }
            }

            """, text);
    }

    [Fact]
    public void PrivateNestedClass_GetsPrivateSiblings_AndStaysOutOfTheRegistrars()
    {
        var result = RunGenerator(Nested);

        var converter = Text(result, "Demo.Outer.PrivateIdSystemTextJsonConverter.g.cs");
        Assert.Contains("private partial class PrivateId", converter, StringComparison.Ordinal);
        Assert.Contains("private sealed class PrivateIdSystemTextJsonConverter : JsonConverter<PrivateId>", converter, StringComparison.Ordinal);

        // The registrars live at namespace level, where a private nested type cannot be named;
        // the attribute on the partial declaration still serves it.
        foreach (var hint in new[]
                 {
                     "ValueObjectJsonConvertersExtensions.g.cs",
                     "ValueObjectJsonTypeInfoResolver.g.cs",
                     "ValueObjectMessagePackResolverExtensions.g.cs",
                 })
        {
            var registrar = Text(result, hint);
            Assert.DoesNotContain("PrivateId", registrar, StringComparison.Ordinal);
            Assert.Contains("global::Demo.Outer.Middle.DeepName", registrar, StringComparison.Ordinal);
        }
    }

    [Fact]
    public void ReferenceType_MessagePackResolver_HasNoNullableArm()
    {
        var text = Text(RunGenerator(Nested), "ValueObjectMessagePackResolverExtensions.g.cs");

        Assert.Contains("return new global::Demo.Outer.Middle.DeepNameMessagePackFormatter();", text, StringComparison.Ordinal);
        Assert.DoesNotContain("Nullable<global::Demo.Outer.Middle.DeepName>", text, StringComparison.Ordinal);
    }

    [Fact]
    public void NestedOutput_HasNoTrailingWhitespace()
    {
        var result = RunGenerator(Nested);

        foreach (var source in result.GeneratedSources)
        {
            var lines = source.SourceText.ToString().Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n');
            Assert.DoesNotContain(lines, static l => l.Length > 0 && char.IsWhiteSpace(l[^1]));
        }
    }

    // The templates carry the line endings of the generator's source file, which differ between
    // a Windows checkout and CI, so compare with the line endings normalised.
    private static void AssertSameText(string expected, string actual) =>
        Assert.Equal(
            expected.Replace("\r\n", "\n", StringComparison.Ordinal),
            actual.Replace("\r\n", "\n", StringComparison.Ordinal));

    private static string Generated(string source, string hintName) => Text(RunGenerator(source), hintName);

    private static string Text(GeneratorRunResult result, string hintName) =>
        result.GeneratedSources.Single(s => string.Equals(s.HintName, hintName, StringComparison.Ordinal))
            .SourceText.ToString();

    private static GeneratorRunResult RunGenerator(string source)
    {
        var compilation = CSharpCompilation.Create(
            "TestAssembly",
            [CSharpSyntaxTree.ParseText(source), CSharpSyntaxTree.ParseText(ValueObjectStub)],
            [
                .. Basic.Reference.Assemblies.Net100.References.All,
                MetadataReference.CreateFromFile(typeof(ZeroAlloc.Serialisation.SystemTextJson.SystemTextJsonSerializer<int>).Assembly.Location),
                MetadataReference.CreateFromFile(typeof(ZeroAlloc.Serialisation.MessagePack.MessagePackSerializer<int>).Assembly.Location),
                MetadataReference.CreateFromFile(typeof(ZeroAlloc.Serialisation.MemoryPack.MemoryPackSerializer<int>).Assembly.Location),
            ],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        var result = CSharpGeneratorDriver.Create(new SerializerGenerator())
            .RunGenerators(compilation)
            .GetRunResult()
            .Results[0];
        Assert.Null(result.Exception);
        return result;
    }
}
