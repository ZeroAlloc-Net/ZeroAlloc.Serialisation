using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using ZeroAlloc.Serialisation.Generator.Models;

namespace ZeroAlloc.Serialisation.Generator;

internal static class DispatcherEmitter
{
    public static void Emit(SourceProductionContext ctx, ImmutableArray<SerializerModel> models, string accessibility)
    {
        if (models.IsDefaultOrEmpty) return;

        EmitDispatcher(ctx, models, accessibility);
        EmitDiExtension(ctx, accessibility);
    }

    private static void EmitDispatcher(SourceProductionContext ctx, ImmutableArray<SerializerModel> models, string accessibility)
    {
        // One instance per serializer, created once and shared by every thread: the generated serializers
        // are sealed and keep no state in instance fields. The System.Text.Json writer cache is [ThreadStatic].
        var instanceFields = string.Join(
            "\n    ",
            models.Select((m, i) =>
                $"private static readonly {SerializerRef(m)} __zaSerializer{i} = new {SerializerRef(m)}();"));

        var serializeCases = string.Join(
            "\n            ",
            models.Select((m, i) => $"case {m.TypeRef} __e: __zaSerializer{i}.Serialize(writer, __e); break;"));

        // typeof(T) == typeof(X) is a constant in each compiled instantiation, so only the matching branch
        // survives. Unsafe.As reinterprets T as X without boxing a struct. Where Unsafe is not in the
        // framework, the (X)(object) cast is the box/unbox pair the JIT removes when it optimizes the method.
        var genericCases = string.Join(
            "\n        ",
            models.Select((m, i) => string.Join(
                "\n        ",
                $"if (typeof(T) == typeof({m.TypeRef}))",
                "{",
                "#if NETCOREAPP3_0_OR_GREATER",
                $"    __zaSerializer{i}.Serialize(writer, global::System.Runtime.CompilerServices.Unsafe.As<T, {m.TypeRef}>(ref value));",
                "#else",
                $"    __zaSerializer{i}.Serialize(writer, ({m.TypeRef})(object)value!);",
                "#endif",
                "    return;",
                "}")));

        var deserializeCases = string.Join(
            "\n        ",
            models.Select((m, i) => m.FormatName == "MessagePack"
                // MessagePack reads ReadOnlyMemory<byte> directly; going through the span overload would
                // copy the payload.
                ? $"if (type == typeof({m.TypeRef})) return {SerializerRef(m)}.DeserializeMemory(data);"
                : $"if (type == typeof({m.TypeRef})) return __zaSerializer{i}.Deserialize(data.Span);"));

        var source = $$"""
            // <auto-generated/>
            #nullable enable
            using System;
            using System.Buffers;
            using global::ZeroAlloc.Serialisation;

            {{accessibility}} sealed partial class SerializerDispatcher : ISerializerDispatcher
            {
                {{instanceFields}}

                /// <inheritdoc/>
                public ReadOnlyMemory<byte> Serialize(object value, Type type)
                {
                    var __writer = new ArrayBufferWriter<byte>();
                    Serialize(__writer, value, type);
                    return __writer.WrittenMemory;
                }

                /// <inheritdoc/>
                public void Serialize(IBufferWriter<byte> writer, object value, Type type)
                {
                    if (writer is null) throw new ArgumentNullException(nameof(writer));

                    switch (value)
                    {
                        {{serializeCases}}
                        default:
                            throw new NotSupportedException(
                                $"No serializer registered for {type.FullName}. " +
                                "Ensure the type is annotated with [ZeroAllocSerializable], or for a closed generic type, " +
                                "declared with [assembly: ZeroAllocSerializable(typeof(...), format)].");
                    }
                }

                /// <inheritdoc/>
                public void Serialize<T>(IBufferWriter<byte> writer, T value)
                {
                    if (writer is null) throw new ArgumentNullException(nameof(writer));

                    {{genericCases}}
                    Serialize(writer, value!, typeof(T));
                }

                /// <inheritdoc/>
                public object? Deserialize(ReadOnlyMemory<byte> data, Type type)
                {
                    {{deserializeCases}}
                    throw new NotSupportedException(
                        $"No serializer registered for {type.FullName}. " +
                        "Ensure the type is annotated with [ZeroAllocSerializable], or for a closed generic type, " +
                        "declared with [assembly: ZeroAllocSerializable(typeof(...), format)].");
                }
            }
            """;

        ctx.AddSource("SerializerDispatcher.g.cs", source);
    }

    private static string SerializerRef(SerializerModel m) => string.IsNullOrEmpty(m.Namespace)
        ? $"global::{m.TypeName}Serializer"
        : $"global::{m.Namespace}.{m.TypeName}Serializer";

    private static void EmitDiExtension(SourceProductionContext ctx, string accessibility)
    {
        var source = $$"""
            // <auto-generated/>
            #nullable enable
            using Microsoft.Extensions.DependencyInjection;
            using Microsoft.Extensions.DependencyInjection.Extensions;
            using global::ZeroAlloc.Serialisation;

            {{accessibility}} static partial class SerializerServiceCollectionExtensions
            {
                public static IServiceCollection AddSerializerDispatcher(
                    this IServiceCollection services)
                {
                    services.TryAddSingleton<ISerializerDispatcher, SerializerDispatcher>();
                    return services;
                }
            }
            """;

        ctx.AddSource("SerializerDispatcherExtensions.g.cs", source);
    }
}
